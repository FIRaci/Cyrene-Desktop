/**
 * Final Markdown rendering main entry point.
 *
 * Data flow:
 *   raw markdown
 *   -> markdown-it parsing (html:false, linkify, breaks:false)
 *   -> KaTeX plugin processing formulas (inline $...$ / block $$...$$)
 *   -> fenced code custom renderer -> Shiki codeToHtml
 *   -> DOMPurify sanitization
 *   -> returns MarkdownRenderResult
 *
 * Fallback strategy:
 *   - Individual Shiki code block failure: degrades that code block only without breaking message
 *   - KaTeX parse failure: displays raw LaTeX text (throwOnError:false) without losing content
 *   - markdown-it general exception: returns { mode:"text", content: raw }
 *   - DOMPurify general exception: returns { mode:"text", content: raw }
 *
 * HTML ownership:
 *   - .code-block wrapper + header generated by this module
 *   - Shiki <pre class="shiki"> placed inside .code-block__code
 *   - Fallback code escaped before HTML insertion
 */

import MarkdownIt from "markdown-it";
import { katex as katexPlugin } from "@mdit/plugin-katex";
import DOMPurify from "dompurify";
import { codeToHtml } from "./code-highlighter";
import { normalizeLang, getLanguageDisplayName } from "./language-normalizer";
import type { MarkdownRenderResult } from "./types";

// ── markdown-it instance (module singleton) ──────────────────

/** Get markdown-it instance (for streaming session usage) */
export function getMd(): MarkdownIt { return md; }

const md: MarkdownIt = new MarkdownIt({
  html: false,
  linkify: true,
  breaks: true,   // Single newline \n → <br>, preserving LLM output linebreaks
  typographer: false,
});

// KaTeX plugin: handles inline $...$ and block $$...$$ math formulas
// throwOnError:false -> Invalid LaTeX displays raw text without crashing
md.use(katexPlugin, { throwOnError: false });

// ── Inline Thought Renderer: /thought/ ───────────────────────
// Matches /thought text/ that is not part of a URL, path, or math formula.
// Wrapped into <span class="pet-bubble__thought-inline chat-thought">/thought/</span>
// Synchronized with Live2D companion bubble styling (#bae6fd).

function isTerminatorWithSlash(ch: number): boolean {
  switch (ch) {
    case 0x0A: /* \n */
    case 0x21: /* ! */
    case 0x23: /* # */
    case 0x24: /* $ */
    case 0x25: /* % */
    case 0x26: /* & */
    case 0x2A: /* * */
    case 0x2B: /* + */
    case 0x2D: /* - */
    case 0x2F: /* / */
    case 0x3A: /* : */
    case 0x3C: /* < */
    case 0x3D: /* = */
    case 0x3E: /* > */
    case 0x40: /* @ */
    case 0x5B: /* [ */
    case 0x5C: /* \ */
    case 0x5D: /* ] */
    case 0x5E: /* ^ */
    case 0x5F: /* _ */
    case 0x60: /* ` */
    case 0x7B: /* { */
    case 0x7D: /* } */
    case 0x7E: /* ~ */
      return true;
    default:
      return false;
  }
}

md.inline.ruler.at("text", (state, silent) => {
  let pos = state.pos;
  while (pos < state.posMax && !isTerminatorWithSlash(state.src.charCodeAt(pos))) {
    pos++;
  }
  if (pos === state.pos) return false;
  if (!silent) {
    state.pending += state.src.slice(state.pos, pos);
  }
  state.pos = pos;
  return true;
});

md.inline.ruler.before("text", "thought", (state, silent) => {
  const start = state.pos;
  const src = state.src;
  if (src.charCodeAt(start) !== 0x2f /* / */) return false;

  // Preceding char check: must not be alphanumeric, :, or /
  if (start > 0) {
    const prev = src.charCodeAt(start - 1);
    if (
      (prev >= 0x30 && prev <= 0x39) || // 0-9
      (prev >= 0x41 && prev <= 0x5a) || // A-Z
      (prev >= 0x61 && prev <= 0x7a) || // a-z
      prev === 0x3a || // :
      prev === 0x2f    // /
    ) {
      return false;
    }
  }

  // Next char check: cannot be whitespace, newline, or slash
  if (start + 1 >= state.posMax) return false;
  const next = src.charCodeAt(start + 1);
  if (next === 0x20 || next === 0x09 || next === 0x0a || next === 0x0d || next === 0x2f) {
    return false;
  }

  // Find closing / on the same line
  let end = -1;
  for (let i = start + 2; i < state.posMax; i++) {
    const code = src.charCodeAt(i);
    if (code === 0x0a || code === 0x0d) break;
    if (code === 0x2f /* / */) {
      const prevCode = src.charCodeAt(i - 1);
      if (prevCode !== 0x20 && prevCode !== 0x09 && prevCode !== 0x2f) {
        // If followed by alphanumeric or slash, likely a path like /foo/bar/
        if (i + 1 < state.posMax) {
          const afterCode = src.charCodeAt(i + 1);
          if (
            (afterCode >= 0x30 && afterCode <= 0x39) ||
            (afterCode >= 0x41 && afterCode <= 0x5a) ||
            (afterCode >= 0x61 && afterCode <= 0x7a) ||
            afterCode === 0x2f
          ) {
            continue;
          }
        }
        end = i;
        break;
      }
    }
  }

  if (end === -1) return false;

  if (!silent) {
    const token = state.push("thought", "span", 0);
    token.attrs = [["class", "pet-bubble__thought-inline chat-thought"]];
    token.content = src.slice(start, end + 1);
  }

  state.pos = end + 1;
  return true;
});

md.renderer.rules.thought = (tokens, idx) => {
  const token = tokens[idx];
  const escaped = escapeHtml(token.content);
  return `<span class="pet-bubble__thought-inline chat-thought">${escaped}</span>`;
};

// ── Link Security: Custom link_open renderer ────────────────

/**
 * Checks whether href is safe. Rejects dangerous protocols like javascript: / data: / vbscript: / file:.
 */
function isAllowedHref(href: string): boolean {
  if (!href) return true; // Empty link (e.g. anchor) allowed
  const lower = href.trim().toLowerCase();
  // Allow http/https/mailto/tel/relative paths/#anchor
  if (/^(https?:|mailto:|tel:|\/|#|\.|\?)/i.test(href)) return true;
  // Explicitly reject dangerous protocols
  if (/^(javascript:|data:|vbscript:|file:)/i.test(lower)) return false;
  // Conservatively reject other unknown protocols
  return false;
}

// Preserve default link_open renderer
const defaultLinkOpenRenderer = md.renderer.rules.link_open
  || function (tokens: MarkdownIt.Token[], idx: number, options, env, self) {
    return self.renderToken(tokens, idx, options);
  };

md.renderer.rules.link_open = function (tokens, idx, options, env, self) {
  const token = tokens[idx];
  const href = token.attrGet("href") ?? "";

  if (!isAllowedHref(href)) {
    token.attrSet("href", "#");
  }

  // External links (http/https) add target + rel
  if (/^https?:\/\//i.test(href) && isAllowedHref(href)) {
    token.attrSet("target", "_blank");
    token.attrSet("rel", "noopener noreferrer");
  }

  return defaultLinkOpenRenderer(tokens, idx, options, env, self);
};

// ── Fenced code custom renderer ──────────────────────────────

const defaultFenceRenderer = md.renderer.rules.fence
  || function (tokens: MarkdownIt.Token[], idx: number, options, env, self) {
    return self.renderToken(tokens, idx, options);
  };

md.renderer.rules.fence = function (tokens, idx, options, env, self) {
  const token = tokens[idx];
  const info = token.info.trim();
  const rawLang = info.split(/\s+/)[0] || "";
  const code = token.content;
  const lang = normalizeLang(rawLang);
  const displayName = getLanguageDisplayName(lang);

  // Synchronously call Shiki highlighter (fallback <pre class="shiki"> if not ready or failed)
  const highlightedHtml = codeToHtml(code, rawLang);

  // Generate .code-block wrapper + header
  // Shiki output <pre class="shiki"> placed inside .code-block__code
  return (
    `<div class="code-block" data-language="${lang}">` +
    `<header class="code-block__header">` +
    `<span class="code-block__language">${displayName}</span>` +
    `<button type="button" class="code-block__copy" title="Copy Code">Copy</button>` +
    `</header>` +
    `<div class="code-block__code">${highlightedHtml}</div>` +
    `</div>`
  );
};

// ── Block-level math formula custom renderer ────────────────
// Default KaTeX outputs <div class="katex-display">...</div>
// Wrapped into <div class="math-block"><div class="math-block__scroll">...</div></div>
// Outer container controls margins and natural height; inner handles horizontal scrolling
// Prevents vertical clipping caused by overflow-x:auto + overflow-y:visible conflicts

const defaultMathBlockRenderer = md.renderer.rules.math_block
  || function (tokens: MarkdownIt.Token[], idx: number, options, env, self) {
    return self.renderToken(tokens, idx, options);
  };

md.renderer.rules.math_block = function (tokens, idx, options, env, self) {
  const innerHtml = defaultMathBlockRenderer(tokens, idx, options, env, self);
  return (
    `<div class="math-block">` +
    `<div class="math-block__scroll">${innerHtml}</div>` +
    `</div>`
  );
};

// ── HTML escape utility ────────────────────────────────────

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}


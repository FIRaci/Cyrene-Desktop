// ── Rendering constants ────────────────────────────────────

/** Character limit for normal markdown-it parsing (degrades to plain text when exceeded) */
const MARKDOWN_PARSE_LIMIT = 40_000;
/** Message total character limit (truncated when exceeded) */
const MESSAGE_CHAR_LIMIT = 140_000;
/** Render version number (incremented when Shiki/KaTeX/renderer rules change to invalidate cache) */
const RENDER_VERSION = 2;
/** LRU cache capacity */
const CACHE_LIMIT = 200;

// ── DOMPurify Allowlist ───────────────────────────────────
// Shiki generated: span, pre, code, style (inline classes)
// KaTeX generated: span, math, semantics, mi, mo, mn, mrow, etc.
// Custom elements: div (.code-block), button (copy), details/summary (collapsible)

const ALLOWED_TAGS = [
  // Basic Markdown
  "p", "br", "hr", "strong", "em", "del", "s", "code", "pre",
  "blockquote", "a", "img",
  "h1", "h2", "h3", "h4", "h5", "h6",
  "ul", "ol", "li",
  "table", "thead", "tbody", "tr", "th", "td",
  // Code block custom
  "div", "span", "button", "details", "summary",
  // KaTeX (math tags output by KaTeX)
  "math", "semantics", "mrow", "mi", "mo", "mn", "msup", "msub",
  "mfrac", "msqrt", "mroot", "mstyle", "merror", "mpadded",
  "mphantom", "mfenced", "menclose", "mspace", "munder", "mover",
  "munderover", "mmultiscripts", "mtable", "mtr", "mtd", "mlabeledtr",
  "maction", "annotation", "annotation-xml",
];

const ALLOWED_ATTRS = [
  // General
  "class", "id", "title", "aria-label", "aria-hidden", "role",
  // Links
  "href", "target", "rel",
  // Images
  "src", "alt", "width", "height",
  // Code blocks
  "data-code", "data-lang",
  // Shiki
  "data-theme",
  // KaTeX
  "data-mathml", "data-annotation",
  // Tables
  "colspan", "rowspan", "align",
  // Foldable
  "open",
  // Copy button
  "type",
  // KaTeX/Shiki inline styles (restricted to trusted zones via uponSanitizeAttribute hook)
  "style",
  // KaTeX MathML
  "xmlns", "encoding",
];

// ── DOMPurify Hook: Allow styles only within trusted renderer zones ──
// KaTeX uses styles for numerators/denominators/integral bounds, Shiki uses styles for coloring
// Raw model output is not permitted to carry custom styles
const TRUSTED_STYLE_ROOTS = ".katex, .katex-display, .shiki, .code-block";

if (typeof DOMPurify.addHook === "function") {
  DOMPurify.addHook("uponSanitizeAttribute", (_node, data) => {
    if (data.attrName !== "style") return;
    const el = _node as Element;
    // Allow inline style only within trusted renderer output regions
    if (typeof el.closest === "function" && el.closest(TRUSTED_STYLE_ROOTS)) {
      return; // Keep
    }
    data.keepAttr = false; // Remove
  });
}

// ── LRU Cache ─────────────────────────────────────────────

const htmlCache = new Map<string, MarkdownRenderResult>();

function cacheGet(key: string): MarkdownRenderResult | undefined {
  const val = htmlCache.get(key);
  if (val) {
    // Move to most recently used
    htmlCache.delete(key);
    htmlCache.set(key, val);
  }
  return val;
}

function cacheSet(key: string, val: MarkdownRenderResult): void {
  if (htmlCache.size >= CACHE_LIMIT) {
    // Evict oldest
    const oldest = htmlCache.keys().next().value;
    if (oldest !== undefined) htmlCache.delete(oldest);
  }
  htmlCache.set(key, val);
}

// ── Plain text fallback ───────────────────────────────────

function renderEscapedPlainText(raw: string): MarkdownRenderResult {
  const escaped = escapeHtml(raw).replace(/\n/g, "<br>");
  return { mode: "html", content: `<p>${escaped}</p>` };
}

// ── Main render function ──────────────────────────────────

/**
 * Renders raw markdown into sanitized HTML.
 *
 * Pipeline: Length protection → markdown-it → DOMPurify → Protocol validation → Cache
 *
 * Returns discriminated union MarkdownRenderResult:
 * - { mode: "html", content }: Render succeeded, content is DOMPurify-sanitized HTML
 * - { mode: "text", content }: Render failed, content is raw markdown, caller uses textContent
 */
export function renderMarkdown(raw: string): MarkdownRenderResult {
  if (!raw || !raw.trim()) {
    return { mode: "html", content: "" };
  }

  // ── Length protection ──
  const text = raw.length > MESSAGE_CHAR_LIMIT
    ? raw.slice(0, MESSAGE_CHAR_LIMIT) + "\n\n[Message too long; truncated]"
    : raw;

  // Ultra-long text fallback: skip markdown-it, escape directly
  if (text.length > MARKDOWN_PARSE_LIMIT) {
    return renderEscapedPlainText(text);
  }

  // ── Cache lookup ──
  // The full source is part of the key. A 32-bit hash alone can collide and
  // display another message's rendered HTML (for example, "Aa" and "BB").
  const cacheKey = `${RENDER_VERSION}:${text}`;
  const cached = cacheGet(cacheKey);
  if (cached) return cached;

  // ── markdown-it rendering ──
  let html: string;
  try {
    html = md.render(text);
  } catch (err) {
    console.warn("[markdown] markdown-it parse failed, fallback to text:", err);
    return renderEscapedPlainText(text);
  }

  // ── DOMPurify sanitization ──
  let sanitized: string;
  try {
    sanitized = DOMPurify.sanitize(html, {
      ALLOWED_TAGS,
      ALLOWED_ATTR: ALLOWED_ATTRS,
      // No scripts/iframes/styles in HTML entities
      // Protocol allowlist: http/https/mailto/tel/relative paths
      ALLOWED_URI_REGEXP: /^(?:(?:https?|mailto|tel):|[^a-z]|[a-z+.\-]+(?:[^a-z+.\-:]|$))/i,
    });
  } catch (err) {
    console.warn("[markdown] DOMPurify sanitize failed, fallback to text:", err);
    return renderEscapedPlainText(text);
  }

  const result: MarkdownRenderResult = { mode: "html", content: sanitized };
  cacheSet(cacheKey, result);
  return result;
}

